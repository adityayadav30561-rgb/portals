"""Writes assets/catalog.js: the data the behaviour layer (assets/app-orders.js) needs to price and check orders in the browser.
Everything comes from data.py, so a price, a stock figure or a credit limit is never typed twice. Run from tools/author:
    PYTHONDONTWRITEBYTECODE=1 python3 runtime_data.py
Run it after any change to prices, stock, credit or the draft orders. tools/check-orders.js compares the browser's totals with the static
screens (the designed draft must produce exactly the totals the Order Builder and Order Confirmation screens show)."""
import json, os
from data import *

def prod_row(p):
    return dict(sku=p[0], name=p[1], finish=p[2], thickness=p[3], kind=p[5], colour=p[6], gloss=bool(p[7]))

PRIMARY_LINES = [('LM-WNT-001', 200), ('LM-ARC-002', 300), ('LM-CAL-003', 80), ('LM-OAK-004', 120), ('LM-SLT-005', 60)]

def lines(l): return [[s, q] for s, q in l]

primary = dict(
    id='primary', supplier='Crestline Laminates', mode='slab', slabs={p[0]: list(p[4]) for p in P},
    supply={s: CSTK[s]['available'] for s in BY}, status={s: ('Low Stock' if CSTK[s]['status'] == 'Low Stock' else 'In Stock') for s in BY},
    rebate=dict(pct=2, label='Festive Volume Rebate', chip='Festive Volume Rebate 2%', before=1990, target=2500),
    gst=9, freight=dict(free_at=450000, fee=4500, name='Company Transport'),
    credit=dict(limit=4000000, outstanding=OUTSTANDING), draft=lines(PRIMARY_LINES),
    series=dict(prefix='ORD-2026-', first=10482, width=5), placed='11:42', requested='31/10/2026', terms='45 days', transport='Company Transport',
    track=[-3, -2, 0], loc='Bhiwandi Warehouse',
    prev=[dict(no=o, date=d, lines=lines(ORDER_LINES[o])) for o, d in [('ORD-2026-10459', '23/10/2026'), ('ORD-2026-10447', '19/10/2026'), ('ORD-2026-10431', '15/10/2026'),
                                                                        ('ORD-2026-10398', '08/10/2026'), ('ORD-2026-10372', '01/10/2026')]],
)
secondary = dict(
    id='secondary', supplier='Distributor Alpha', mode='flat', price={p[0]: dp(p[0]) for p in P},
    supply={s: BY[s][10] for s in BY}, status={s: BY[s][13] for s in BY}, rebate=None,
    gst=9, freight=dict(free_at=0, fee=0, name='Distributor Transport'),
    credit=dict(limit=BRV_LIMIT, outstanding=BRV_OWES), draft=lines(NEW_LINES),
    series=dict(prefix='SAL-2026-', first=3042, width=4), placed='16:05', requested='30/10/2026', terms='30 days', transport='Distributor Transport',
    track=[-2, -2, 0], loc='Shop and Godown, Hadapsar, Pune',
    prev=[dict(no=s['number'], date=s['date'], lines=lines(s['lines'])) for s in BRV_SALES],
)
tertiary = dict(
    id='tertiary', supplier='Dealer Bravo', mode='flat', price={p[0]: rp(p[0]) for p in P},
    supply={s: BSTOCK[s]['available'] for s in BY}, status={s: BSTOCK[s]['status'] for s in BY}, rebate=None,
    gst=9, freight=dict(free_at=0, fee=0, name='Dealer Transport'),
    credit=dict(limit=CHR_LIMIT, outstanding=CHR_OWES), draft=lines(PEND_ORDER['lines']),
    series=dict(prefix='TSL-2026-', first=413, width=4), placed='11:20', requested='28/10/2026', terms='15 days', transport='Dealer Transport',
    track=[-1, -1, 0], loc='Shop 12, MG Road, Camp, Pune',
    prev=[dict(no=s['number'], date=s['date'], lines=lines(s['lines'])) for s in CHR_TS],
)

# credit of the parties a sale can be recorded for (Primary: dealers of Distributor Alpha; Secondary: retailers of Dealer Bravo)
parties = dict(
    primary={f'{d[1]}, {d[2]}': dict(limit=d[9], owes=DEALER_OWES[d[0]]) for d in DEALERS},
    secondary={f'{r[1]}, {r[3]}': dict(limit=r[6], owes=RTL_OWES[r[0]]) for r in RETAILERS},
)
catalog = dict(products=[prod_row(p) for p in P], portals=dict(primary=primary, secondary=secondary, tertiary=tertiary), parties=parties)
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', 'assets', 'catalog.js')
open(out, 'w').write('/* Generated by tools/author/runtime_data.py from data.py: prices, stock, rebate and credit rules, draft orders. Edit the generator, not this file. */\n'
                      'window.CATALOG = ' + json.dumps(catalog, ensure_ascii=False, separators=(',', ':')) + ';\n')
print('wrote', os.path.normpath(out), len(json.dumps(catalog)), 'bytes')
